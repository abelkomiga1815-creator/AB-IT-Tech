package com.abittech.platform.document.service;

import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;

import com.abittech.platform.config.StorageProperties;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.core.io.FileSystemResource;
import org.springframework.core.io.Resource;
import org.springframework.stereotype.Component;

/**
 * Keeps uploaded files in one directory on the server's disk. Files are addressed only by the
 * random storage key generated by the application, and every path is checked to stay inside the
 * directory. Replace this class (keeping its three methods) to move to object storage later.
 */
@Component
public class LocalDocumentStorage {

    private static final Logger log = LoggerFactory.getLogger(LocalDocumentStorage.class);

    private final Path root;

    public LocalDocumentStorage(StorageProperties properties) {
        this.root = Path.of(properties.documentsDir()).toAbsolutePath().normalize();
        try {
            Files.createDirectories(root);
        } catch (IOException ex) {
            throw new UncheckedIOException("Cannot create the documents directory", ex);
        }
    }

    public void store(String key, InputStream content) {
        try {
            Files.copy(content, resolve(key), StandardCopyOption.REPLACE_EXISTING);
        } catch (IOException ex) {
            throw new UncheckedIOException("Could not store the uploaded file", ex);
        }
    }

    /** @return the stored file, or {@code null} when it does not exist on disk */
    public Resource load(String key) {
        Path path = resolve(key);
        return Files.isReadable(path) ? new FileSystemResource(path) : null;
    }

    /** Deletes the file; a missing file is not an error. */
    public void delete(String key) {
        try {
            Files.deleteIfExists(resolve(key));
        } catch (IOException ex) {
            log.warn("Could not delete stored file ({})", ex.getClass().getSimpleName());
        }
    }

    private Path resolve(String key) {
        Path path = root.resolve(key).normalize();
        if (!path.startsWith(root) || path.equals(root)) {
            throw new IllegalArgumentException("Invalid storage key");
        }
        return path;
    }
}
